// Filter out furniture, barber supplies, mirrors, chairs, barber tools
const isIrrelevant = (p) => {
  const cat = (p.category || '').toLowerCase();
  const name = (p.name || '').toLowerCase();
  if (cat.includes('furniture') || cat.includes('barber')) return true;
  if (name.includes('chair') || name.includes('table') || name.includes('mirror') ||
      name.includes('barber') || name.includes('sofa') || name.includes('stool') ||
      name.includes('bed') || name.includes('trolley') || name.includes('tray') ||
      name.includes('clipper') || name.includes('trimmer') || name.includes('shaver') ||
      name.includes('holster') || name.includes('cape')) {
    return true;
  }
  return false;
};

// Clean and categorize existing products
const retainedProducts = [];
existingProducts.forEach((p) => {
  if (isIrrelevant(p)) return;
  const copy = { ...p };
  // Migrate Professional Equipment to Beauty Tools
  if (copy.category === 'Professional Equipment') {
    copy.category = 'Beauty Tools';
    copy.tags = copy.tags ? [...copy.tags.filter(t => t !== 'professional equipment'), 'beauty tools'] : ['beauty tools'];
  }
  // Group Waxing and Hair Color & Treatment under Skin Care or Hair Care or Cosmetics as appropriate
  if (copy.category === 'Hair Color & Treatment') {
    copy.category = 'Hair Care';
    copy.subcategory = copy.subcategory || 'Color & Treatment';
  }
  if (copy.category === 'Waxing') {
    copy.category = 'Bath & Body';
    copy.subcategory = 'Depilatory & Waxing';
  }
  retainedProducts.push(copy);
});

